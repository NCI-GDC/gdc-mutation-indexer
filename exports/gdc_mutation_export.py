import abc
import logging
from typing import Collection, Dict, Iterable, Mapping, NamedTuple

import pyspark
import networkx as nx
from pyspark import sql

import config
from exports.builders import base_builder, bases
from exports.constants import build

logging.basicConfig(format=config.LOG_FORMAT)

logger = logging.getLogger(__name__)


class Builders(NamedTuple):
    builders: Iterable[bases.Builder]
    index_builders: Mapping[build.IndexType, base_builder.BaseBuilder]


class Export(abc.ABC):
    """
    The main entry point into the index export process for the mutation indices
    """

    __slots__ = ("_spark_context", "_index_types", "_builders", "_index_builders")

    def __init__(
        self,
        spark_context: pyspark.SparkContext,
        index_types: Collection[build.IndexType],
        builders: Builders,
    ) -> None:
        self._spark_context = spark_context
        self._index_types = index_types
        self._builders = builders.builders
        self._index_builders = builders.index_builders

    def _get_builders(self) -> Iterable[bases.Builder]:
        builders = nx.DiGraph()

        builders.add_nodes_from((b.output, {"builder": b}) for b in self._builders)
        builders.add_edges_from((i, b.output) for b in self._builders for i in b.inputs)

        return (builders.nodes[n]["builder"] for n in nx.topological_sort(builders))

    def _build_data_frames(self) -> Dict[str, sql.DataFrame]:
        """
        Builds all the data frames generated by the builders given in this instance's
        _builders field.

        Returns:
            The data frames generated by the builder objects.
        """
        inputs: Dict[str, sql.DataFrame] = {}
        builders = self._get_builders()

        for builder in builders:
            output = builder.output
            self._spark_context.setJobGroup(output.name, f"Build {output}")

            df = builder.build(**inputs)
            inputs[output.to_param()] = df

        return inputs

    def run_export(
        self,
    ) -> None:
        """
        Executes the export configured data by running the required builders.
        """
        inputs = self._build_data_frames()

        for index_type in self._index_types:
            if index_type not in self._index_builders:
                raise ValueError(f"No builder is configured for index: {index_type}.")

            self._spark_context.setJobGroup(index_type.name, f"Build {index_type}")
            self._index_builders[index_type].build(**inputs).load()

        logger.info("Mutation Indexer finished successfully")
